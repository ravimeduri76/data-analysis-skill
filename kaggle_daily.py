#!/usr/bin/env python3
"""Kaggle Daily Analysis Pipeline.

Discovers one new Kaggle dataset per day, runs analysis hooks,
persists results to PostgreSQL, generates a report, and feeds
learnings back into the skill.

Usage:
    python kaggle_daily.py                    # full run
    python kaggle_daily.py --dry-run          # discover only
    python kaggle_daily.py --strategy votes   # override sort mode
    python kaggle_daily.py --notify           # send WhatsApp summary
"""
