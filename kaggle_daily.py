_REPORT_TEMPLATE = """\
# Kaggle Daily Analysis Report -- {date}

**Dataset:** [{title}]({url})
**Slug:** `{slug}`
**Domain:** {domain} (confidence: {confidence}, method: {method})
**Quality:** {quality_score}/100 (Grade: {grade})

## Dataset Profile
- Rows: {rows} | Columns: {cols}
- Anomalies: {n_anomalies} | Strong correlations: {n_correlations}

## Key Insights
{insights_block}

## ML Experiment Results
{ml_block}

## What-If Suggestions
{whatif_block}

## Self-Improvement Applied
{improvement_block}

---
*Generated by Kaggle Daily Pipeline at {timestamp}*
"""


def _quality_grade(score: float) -> str:
    if score >= 90:
        return "A"
    if score >= 75:
        return "B"
    if score >= 60:
        return "C"
    if score >= 40:
        return "D"
    return "F"


def _generate_report(ctx: dict, out_dir: Path) -> str:
    """Write the daily markdown report and return its path."""
    insights = ctx.get("insights", [])
    insights_block = "\n".join(
        f"{i+1}. {c.finding} -- Method: {c.method}, Confidence: {c.confidence}"
        for i, c in enumerate(insights)
    ) if insights else "_No insights generated._"

    whatifs = ctx.get("what_ifs", [])
    whatif_block = "\n".join(
        f"- **{w.get('missing_data', w.get('scenario', 'N/A'))}**: "
        f"{w.get('what_unlocks', w.get('impact', 'N/A'))}"
        for w in whatifs
    ) if whatifs else "_No what-if suggestions._"

    improvement_block = ctx.get("improvement_text", "_No self-improvement applied._")

    qr = ctx.get("quality_report")
    avg_quality = round(qr["quality_score"].mean(), 1) if qr is not None and "quality_score" in qr.columns else 0
    grade = _quality_grade(avg_quality)

    ml_block = ctx.get("ml_summary", "_No ML experiments run._")

    md = _REPORT_TEMPLATE.format(
        date=ctx["date"],
        title=ctx["title"],
        url=ctx["url"],
        slug=ctx["slug"],
        domain=ctx["domain_ctx"].get("domain", "Unknown"),
        confidence=ctx["domain_ctx"].get("confidence", "?"),
        method=ctx["domain_ctx"].get("method", "?"),
        quality_score=avg_quality,
        grade=grade,
        rows=ctx["rows"],
        cols=ctx["cols"],
        n_anomalies=ctx.get("n_anomalies", 0),
        n_correlations=ctx.get("n_correlations", 0),
        insights_block=insights_block,
        ml_block=ml_block,
        whatif_block=whatif_block,
        improvement_block=improvement_block,
        timestamp=datetime.now(timezone.utc).isoformat(),
    )
    # ASCII-safe
    md = md.encode("ascii", errors="replace").decode("ascii")

    report_path = out_dir / f"report_{ctx['date'].replace('-', '')}.md"
    report_path.write_text(md, encoding="utf-8")
    log.info("Report saved: %s", report_path)
    return str(report_path)


# ---------------------------------------------------------------------------
# Notification (optional WhatsApp via Openclaw gateway)
# ---------------------------------------------------------------------------
def _notify(summary: str) -> None:
    """Send a short summary via Openclaw gateway."""
    import urllib.request
    import urllib.error

    gateway_url = "http://localhost:18789/api/send"
    payload = json.dumps({
        "channel": "whatsapp",
        "to": "+919866072293",
        "message": summary,
    }).encode("utf-8")

    req = urllib.request.Request(
        gateway_url,
        data=payload,
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=10) as resp:
            log.info("Notification sent (status %d)", resp.status)
    except (urllib.error.URLError, OSError) as exc:
        log.warning("Notification failed (non-fatal): %s", exc)


