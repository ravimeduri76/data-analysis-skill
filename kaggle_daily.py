def phase_discover(strategy: str, tracking: dict) -> Optional[dict]:
    """Phase 1: Find a new dataset."""
    from hooks.kaggle_discovery import discover_dataset

    analyzed_slugs = set(tracking.keys())
    domain_history = [
        v.get("domain", "General")
        for v in sorted(tracking.values(), key=lambda x: x.get("date", ""))
    ]

    candidate = discover_dataset(analyzed_slugs, strategy, domain_history)
    if candidate:
        log.info("Phase 1 DONE — candidate: %s", candidate["slug"])
    else:
        log.warning("Phase 1 — no candidate found")
    return candidate


def phase_download(candidate: dict, day_dir: Path) -> Optional[str]:
    """Phase 2: Download and pick best tabular file."""
    from hooks.kaggle_discovery import download_dataset, pick_best_file

    raw_dir = day_dir / "raw_data"
    files = download_dataset(candidate["slug"], str(raw_dir))
    if not files:
        log.error("Phase 2 — download returned no files")
        return None

    best = pick_best_file(str(raw_dir))
    if not best:
        log.error("Phase 2 — no tabular file found in download")
        return None

    log.info("Phase 2 DONE — best file: %s", best)
    return best


def phase_analyze(data_path: str, candidate: dict) -> dict:
    """Phase 3: Run Workflow A + C analysis hooks."""
    from loader import load_dataframe
    from profiler import profile_dataframe
    from classifier import classify_columns
    from hooks.domain_detector import detect_domain
    from hooks.missing_values import missing_report
    from hooks.data_quality import quality_report, quality_commentary
    from hooks.correlation import top_correlations
    from hooks.outliers import outlier_report
    from hooks.anomaly_detection import detect_anomalies
    from hooks.explainability import explain_quality, explain_missing, explain_anomalies
    from hooks.what_if import suggest_what_if
    from hooks.trace_writer import AnalysisTrace

    api_key = os.environ.get("ANTHROPIC_API_KEY")

    # Load
    log.info("Loading %s", data_path)
    df = load_dataframe(data_path)
    rows, cols = df.shape
    log.info("Loaded: %d rows x %d cols", rows, cols)

    # Profile & classify
    profile = profile_dataframe(df)
    col_classes = classify_columns(df)

    # Domain detection
    domain_ctx = detect_domain(df, anthropic_api_key=api_key,
                               user_query=f"Kaggle dataset: {candidate['title']}")
    log.info("Domain: %s (confidence=%s, method=%s)",
             domain_ctx["domain"], domain_ctx["confidence"], domain_ctx["method"])

    # Trace
    trace = AnalysisTrace(
        dataset_path=data_path,
        query=f"Kaggle daily analysis of {candidate['title']}",
        domain_ctx=domain_ctx,
    )
    trace.log_step("load", "Loaded dataset", {"path": data_path}, f"{rows} rows x {cols} cols")
    trace.log_step("profile", "Profiled columns", {}, f"{len(profile)} columns profiled")
    trace.log_step("classify", "Classified columns", {}, json.dumps({k: len(v) for k, v in col_classes.items()}, default=str))

    # Missing values
    miss_df = missing_report(df)
    trace.log_step("missing", "Missing value report", {}, f"{(miss_df['null_pct'] > 0).sum()} cols with nulls")

    # Data quality
    qr = quality_report(df)
    qr_text = quality_commentary(qr)
    trace.log_step("quality", "Data quality report", {}, qr_text[:200])

    # Correlations (need at least 2 numeric columns)
    numeric_cols = df.select_dtypes(include="number").columns
    if len(numeric_cols) >= 2:
        top_corr = top_correlations(df)
        n_correlations = len(top_corr) if top_corr is not None and not (hasattr(top_corr, 'empty') and top_corr.empty) else 0
    else:
        top_corr = None
        n_correlations = 0
    trace.log_step("correlations", "Top correlations", {}, f"{n_correlations} strong correlations")

    # Outliers
    out_df = outlier_report(df)
    trace.log_step("outliers", "Outlier report", {}, f"{len(out_df)} outlier records")

    # Anomaly detection (Workflow C core)
    annotated_df, anomaly_summ = detect_anomalies(df)
    n_anomalies = len(anomaly_summ) if anomaly_summ is not None else 0
    trace.log_step("anomalies", "Anomaly detection", {}, f"{n_anomalies} anomaly types found")

    # Explainability
    insights = []
    insights.extend(explain_quality(qr, rows))
    insights.extend(explain_missing(miss_df, rows))
    if anomaly_summ is not None and len(anomaly_summ) > 0:
        insights.extend(explain_anomalies(anomaly_summ, domain_ctx))

    for card in insights:
        trace.log_insight(card)

    # What-if suggestions
    what_ifs = suggest_what_if(domain_ctx, df, anthropic_api_key=api_key)
    trace.log_step("what_if", "What-if suggestions", {}, f"{len(what_ifs)} suggestions")

    log.info("Phase 3 DONE — %d insights, %d what-ifs", len(insights), len(what_ifs))

    return {
        "df": df,
        "rows": rows,
        "cols": cols,
        "profile": profile,
        "col_classes": col_classes,
        "domain_ctx": domain_ctx,
        "trace": trace,
        "quality_report": qr,
        "quality_text": qr_text,
        "n_anomalies": n_anomalies,
        "n_correlations": n_correlations,
        "insights": insights,
        "what_ifs": what_ifs,
    }


def phase_ml_experiment(analysis: dict, day_dir: Path, candidate: dict) -> Optional[dict]:
    """Phase 3b: Autoresearch-style ML experiment loop."""
    try:
        from hooks.ml_experiment import (
            select_target, build_feature_matrix,
            run_experiment_loop, append_results_tsv,
            render_experiment_summary,
        )
    except ImportError:
        log.warning("Phase 3b — ml_experiment hook not available, skipping")
        return None

    df = analysis["df"]
    col_classes = analysis["col_classes"]
    domain_ctx = analysis["domain_ctx"]
    trace = analysis["trace"]

    # 1. Select target
    target_info = select_target(df, col_classes, domain_ctx)
    if target_info is None:
        log.info("Phase 3b — no suitable prediction target found, skipping ML")
        trace.log_step("ml_target", "ML target selection", {}, "No suitable target found")
        return None

    target_col = target_info["col"]
    task_type = target_info["task_type"]
    log.info("Phase 3b — target: %s (task=%s, rationale=%s)",
             target_col, task_type, target_info["rationale"])
    trace.log_step("ml_target", "ML target selection",
                   {"target": target_col, "task_type": task_type},
                   target_info["rationale"])

    # 2. Build feature matrix
    id_cols = col_classes.get("identifiers", [])
    try:
        X, y, feature_names = build_feature_matrix(df, target_col, id_cols)
    except Exception as exc:
        log.error("Phase 3b — feature matrix build failed: %s", exc)
        trace.log_step("ml_features", "ML feature matrix", {}, f"FAILED: {exc}")
        return None

    trace.log_step("ml_features", "ML feature matrix",
                   {"n_features": len(feature_names), "n_rows": len(X)},
                   f"{len(feature_names)} features, {len(X)} rows")

    # 3. Run research project (4-phase orchestrator) with fallback to experiment loop
    try:
        from hooks.research_orchestrator import run_research_project
        result = run_research_project(
            df, col_classes, domain_ctx,
            target_col=target_col,
            max_iterations=3,
            budget_limit={"max_trials": 15, "max_seconds": 300},
            out_dir=day_dir,
            anthropic_api_key=os.environ.get("ANTHROPIC_API_KEY"),
        )
        log.info("Phase 3b — research orchestrator completed "
                 "(iterations=%s, stop=%s)",
                 result.get("trace", {}).get("iterations", "?"),
                 result.get("trace", {}).get("stop_reason", "?"))
    except ImportError:
        log.info("Phase 3b — research_orchestrator not available, falling back to experiment loop")
        try:
            result = run_experiment_loop(
                X, y, feature_names, task_type=task_type, max_trials=8,
                anthropic_api_key=os.environ.get("ANTHROPIC_API_KEY"),
                domain_ctx=domain_ctx,
                out_dir=day_dir,
                n_rounds=2,
            )
        except Exception as exc:
            log.error("Phase 3b — experiment loop failed: %s", exc)
            trace.log_step("ml_loop", "ML experiment loop", {}, f"FAILED: {exc}")
            return None
    except Exception as exc:
        log.error("Phase 3b — research orchestrator failed: %s", exc)
        trace.log_step("ml_loop", "ML research project", {}, f"FAILED: {exc}")
        return None

    # 4. Log each trial + best as insight
    for t in result["trials"]:
        trace.log_step(
            f"ml_trial_{t['trial_id']}", f"Trial {t['model']}",
            t["metrics"], f"status={t['status']}",
        )

    best = result.get("best_trial", {})
    if best and best.get("metrics"):
        from hooks.explainability import InsightCard
        card = InsightCard(
            finding=f"Best ML model: {best['metrics']['Model']} "
                    f"({result['primary_metric']}={best['metrics'].get(result['primary_metric'], 'N/A')})",
            metric=str(best["metrics"].get(result["primary_metric"], "")),
            method="ml_experiment",
            confidence="high" if result["incumbent_metric"] > 0.5 else "medium",
            columns_used=target_col,
            source_hook="ml_experiment",
            rows_analyzed=len(analysis["df"]),
            total_rows=len(analysis["df"]),
            caveats="",
            sql_equivalent="",
        )
        trace.log_insight(card)

    # 5. Write TSV
    domain = domain_ctx.get("domain", "Unknown")
    slug = candidate.get("slug", "unknown")

    # Per-dataset TSV
    local_tsv = append_results_tsv(
        result["trials"], day_dir / "experiments.tsv",
        dataset_name=slug, domain=domain, target_col=target_col,
    )

    # Global cross-dataset TSV
    global_tsv = append_results_tsv(
        result["trials"], _OUTPUT_ROOT / "ml_experiments.tsv",
        dataset_name=slug, domain=domain, target_col=target_col,
    )

    # 6. Render summary
    summary = render_experiment_summary(result)
    trace.log_step("ml_summary", "ML experiment summary", {},
                   summary[:200] if summary else "empty")

    log.info("Phase 3b DONE — %d trials, best=%s (%s=%.4f)",
             len(result["trials"]),
             best.get("metrics", {}).get("Model", "N/A"),
             result["primary_metric"],
             result["incumbent_metric"])

    result["summary_text"] = summary
    result["target_info"] = target_info
    return result


def phase_persist(analysis: dict) -> Optional[str]:
    """Phase 4: Save to PostgreSQL."""
    try:
        from hooks.db_store import get_connection, init_db, save_run
    except ImportError:
        log.warning("Phase 4 — psycopg2 not available, skipping DB persist")
        return None

    postgres_url = os.environ.get("POSTGRES_URL")
    if not postgres_url:
        log.warning("Phase 4 — POSTGRES_URL not set, skipping DB persist")
        return None

    try:
        conn = get_connection(postgres_url)
        init_db(conn)

        qr = analysis["quality_report"]
        avg_quality = round(qr["quality_score"].mean(), 1) if "quality_score" in qr.columns else 0

        ml_result = analysis.get("ml_result")
        ml_finding = ""
        if ml_result and ml_result.get("best_trial"):
            bt = ml_result["best_trial"]
            pm = ml_result["primary_metric"]
            ml_finding = (
                f" Best ML: {bt['metrics'].get('Model', '?')} "
                f"({pm}={bt['metrics'].get(pm, '?')})."
            )

        findings = (
            f"Domain: {analysis['domain_ctx']['domain']}. "
            f"Quality: {avg_quality}/100. "
            f"{analysis['n_anomalies']} anomaly types, "
            f"{len(analysis['insights'])} insights."
            f"{ml_finding}"
        )

        workflows = ["A", "C"]
        a_type = "profile"
        if analysis.get("ml_result"):
            workflows.append("E")
            a_type = "ml_experiment"

        run_id = save_run(
            conn=conn,
            trace=analysis["trace"],
            domain_ctx=analysis["domain_ctx"],
            findings_summary=findings,
            analysis_type=a_type,
            workflows_run=workflows,
            row_count=analysis["rows"],
            col_count=analysis["cols"],
            what_if_suggestions=analysis["what_ifs"],
        )
        conn.close()
        log.info("Phase 4 DONE — run_id: %s", run_id)
        return run_id
    except Exception as exc:
        log.error("Phase 4 — DB persist failed (non-fatal): %s", exc)
        return None


def phase_self_improve(analysis: dict, data_path: str, candidate: dict) -> str:
    """Phase 5: Feed learnings back into the skill."""
    try:
        from hooks.self_improver import run_self_improvement, improvement_report
    except ImportError:
        log.warning("Phase 5 — self_improver not available")
        return "_Self-improvement unavailable._"

    api_key = os.environ.get("ANTHROPIC_API_KEY")

    run_meta = {
        "dataset_path": data_path,
        "query": f"Kaggle daily analysis of {candidate['title']}",
        "domain_detected": analysis["domain_ctx"].get("domain", "General"),
        "domain_method": analysis["domain_ctx"].get("method", "heuristic"),
        "domain_confidence": analysis["domain_ctx"].get("confidence", "low"),
        "domain_correct": True,  # auto-accept for unattended runs
        "domain_actual": analysis["domain_ctx"].get("domain", "General"),
        "analysis_type": "ml_experiment" if analysis.get("ml_result") else "profile",
        "workflows_run": ["A", "C"] + (["E"] if analysis.get("ml_result") else []),
        "row_count": analysis["rows"],
        "col_count": analysis["cols"],
        "column_names": list(analysis["df"].columns),
        "issues": [],
        "findings_summary": f"{len(analysis['insights'])} insights, {analysis['n_anomalies']} anomalies",
    }

    try:
        result = run_self_improvement(run_meta, anthropic_api_key=api_key, auto_apply=True)
        text = improvement_report(result)
        log.info("Phase 5 DONE — %s", text[:200])
        return text
    except Exception as exc:
        log.error("Phase 5 — self-improvement failed (non-fatal): %s", exc)
        return f"_Self-improvement error: {exc}_"


