# ---------------------------------------------------------------------------
# Logging
# ---------------------------------------------------------------------------
def _setup_logging() -> None:
    _OUTPUT_ROOT.mkdir(parents=True, exist_ok=True)
    fmt = "%(asctime)s  %(levelname)-8s  %(name)s  %(message)s"
    handlers: list[logging.Handler] = [
        logging.StreamHandler(sys.stdout),
        logging.handlers.RotatingFileHandler(
            _LOG_FILE, maxBytes=2 * 1024 * 1024, backupCount=3, encoding="utf-8",
        ),
    ]
    logging.basicConfig(level=logging.INFO, format=fmt, handlers=handlers)


import logging.handlers  # noqa: E402 (needed before _setup_logging call)

log = logging.getLogger("kaggle_daily")


# ---------------------------------------------------------------------------
# .env loader
# ---------------------------------------------------------------------------
def _load_env() -> None:
    """Load environment variables from .env file."""
    if not _ENV_FILE.exists():
        return
    try:
        from dotenv import load_dotenv
        load_dotenv(_ENV_FILE)
    except ImportError:
        # Manual fallback
        for line in _ENV_FILE.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            k, v = line.split("=", 1)
            os.environ.setdefault(k.strip(), v.strip())


# ---------------------------------------------------------------------------
# Tracking (slug dedup)
# ---------------------------------------------------------------------------
def _load_tracking() -> dict:
    """Load analyzed_datasets.json → {slug: {date, domain, ...}}."""
    if _TRACKING_FILE.exists():
        try:
            return json.loads(_TRACKING_FILE.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            log.warning("Corrupted tracking file — starting fresh")
    return {}


def _save_tracking(data: dict) -> None:
    _TRACKING_FILE.parent.mkdir(parents=True, exist_ok=True)
    _TRACKING_FILE.write_text(
        json.dumps(data, indent=2, default=str), encoding="utf-8",
    )


