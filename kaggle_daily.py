# Main orchestrator
# ---------------------------------------------------------------------------
def main() -> int:
    parser = argparse.ArgumentParser(description="Kaggle Daily Analysis Pipeline")
    parser.add_argument("--dry-run", action="store_true",
                        help="Discover only, no download or analysis")
    parser.add_argument("--strategy", choices=["hottest", "votes", "updated", "auto"],
                        default="auto", help="Override sort mode")
    parser.add_argument("--notify", action="store_true",
                        help="Send WhatsApp summary via Openclaw gateway")
    args = parser.parse_args()

    _setup_logging()
    _load_env()

    today = datetime.now().strftime("%Y-%m-%d")
    log.info("=== Kaggle Daily Pipeline — %s ===", today)

    tracking = _load_tracking()

    # Phase 1: Discover
    candidate = phase_discover(args.strategy, tracking)
    if candidate is None:
        log.error("No dataset found — aborting")
        return 1

    if args.dry_run:
        print(f"\n[DRY RUN] Candidate dataset:")
        print(f"  Slug:   {candidate['slug']}")
        print(f"  Title:  {candidate['title']}")
        print(f"  Size:   {candidate['size']:,} bytes")
        print(f"  URL:    {candidate['url']}")
        print(f"  Domain: {candidate.get('domain_hint', 'Unknown')}")
        return 0

    # Phase 2: Download
    day_dir = _OUTPUT_ROOT / today
    day_dir.mkdir(parents=True, exist_ok=True)

    data_path = phase_download(candidate, day_dir)
    if data_path is None:
        log.error("Download failed — aborting")
        return 1

    # Phase 3: Analyze
    try:
        analysis = phase_analyze(data_path, candidate)
    except Exception as exc:
        log.error("Phase 3 — analysis failed: %s", exc, exc_info=True)
        return 1

    # Phase 3b: ML experiment loop
    try:
        ml_result = phase_ml_experiment(analysis, day_dir, candidate)
        if ml_result:
            analysis["ml_result"] = ml_result
    except Exception as exc:
        log.error("Phase 3b — ML experiment failed (non-fatal): %s", exc, exc_info=True)
        ml_result = None

    # Phase 4: Persist to DB
    run_id = phase_persist(analysis)

    # Phase 5: Self-improve
    improvement_text = phase_self_improve(analysis, data_path, candidate)

    # Phase 6: Report
    domain = analysis["domain_ctx"].get("domain", "Unknown")
    qr = analysis["quality_report"]
    avg_quality = round(qr["quality_score"].mean(), 1) if "quality_score" in qr.columns else 0

    # Save trace
    try:
        trace_json, trace_md = analysis["trace"].save_manifest(str(day_dir))
        log.info("Trace saved: %s, %s", trace_json, trace_md)
    except Exception as exc:
        log.warning("Trace save failed (non-fatal): %s", exc)

    report_ctx = {
        "date": today,
        "title": candidate["title"],
        "url": candidate["url"],
        "slug": candidate["slug"],
        "domain_ctx": analysis["domain_ctx"],
        "rows": analysis["rows"],
        "cols": analysis["cols"],
        "n_anomalies": analysis["n_anomalies"],
        "n_correlations": analysis["n_correlations"],
        "quality_report": qr,
        "insights": analysis["insights"],
        "what_ifs": analysis["what_ifs"],
        "improvement_text": improvement_text,
        "ml_summary": ml_result["summary_text"] if ml_result else "_No ML experiments run._",
    }
    report_path = phase_report(report_ctx, day_dir)

    # Phase 7: Track
    phase_track(tracking, candidate, domain)

    # Phase 8: Chart + Notify
    chart_path = _generate_summary_chart(ml_result, day_dir)
    phase_notify(candidate, domain, avg_quality, analysis, ml_result,
                 improvement_text, chart_path, args.notify)

    log.info("=== Pipeline complete — %s ===", candidate["slug"])
    print(f"\nDone. Report: {report_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
